//! Generate the frozen test vectors PROTOCOL.md 14.1 requires.
//!
//! Writes `docs/test-vectors.txt`. The committed file is the authority: it is
//! what a second implementation validates against, and `tests/vectors.rs`
//! checks that this implementation still reproduces it byte for byte.
//!
//! Run with: cargo run --bin catp-vectors > docs/test-vectors.txt

use catp::wire::Datagram;
use catp::*;

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// One accepted vector: inputs, derived key, and the exact bytes on the wire.
fn accept(name: &str, secret: &DeviceSecret, epoch: u32, dir: Direction, dg: &Datagram) {
    let wire = dg.encode(secret, epoch, dir, 65535).expect("vector must encode");
    let key = secret.epoch_key(dg.sender_id, epoch, dir);
    println!("# {name}");
    println!("kind         accept");
    println!("device_secret {}", hex(&secret.0));
    println!("sender_id    {:08x}", dg.sender_id);
    println!("epoch_id     {epoch}");
    println!("direction    {:02x}", dir as u8);
    println!("cipher_id    {:02x}", dg.cipher_id);
    println!("msg_type     {:02x}", dg.msg_type);
    println!("offset       {}", dg.datagram_offset);
    println!("epoch_key    {}", hex(&key));
    println!("auth_header  {}", hex(&dg.auth_header(epoch)));
    println!("wire         {}", hex(&wire));
    println!("wire_len     {}", wire.len());
    println!();
}

fn main() {
    let s = DeviceSecret([
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f,
    ]);
    let id = 0x1234_5678u32;
    let epoch = 13_281_250u32;
    let n2c = Direction::NodeToCollector;

    println!("# CATP v1 frozen test vectors (PROTOCOL.md 14.1)");
    println!("# Generated by `cargo run --bin catp-vectors`. Do not hand-edit.");
    println!("# All values hex, big-endian, no separators.");
    println!();

    // --- one accepted datagram per msg_type, per implemented cipher ---
    for cipher in [CipherId::HmacSha256T64, CipherId::HmacSha256T32] {
        let tag = cipher.tag_len();
        accept(
            &format!("NUMBER, positive float, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::number(cipher, id, epoch, 4096, "23.5").unwrap(),
        );
        accept(
            &format!("NUMBER, negative, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::number(cipher, id, epoch, 4097, "-0.25").unwrap(),
        );
        accept(
            &format!("NUMBER, zero, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::number(cipher, id, epoch, 0, "0").unwrap(),
        );
        accept(
            &format!("MESSAGE, single record, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::data(
                MsgType::Message,
                cipher,
                id,
                epoch,
                100,
                vec![Record::new(Format::None, 1, vec![0xde, 0xad])],
            )
            .unwrap(),
        );
        accept(
            &format!("MESSAGE, three records, mixed formats, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::data(
                MsgType::Message,
                cipher,
                id,
                epoch,
                200,
                vec![
                    Record::new(Format::None, 1, vec![0x01]),
                    Record::new(Format::Cbor, 2, vec![0x02, 0x03]),
                    Record::new(Format::MsgPack, 0xff, vec![0x04, 0x05, 0x06]),
                ],
            )
            .unwrap(),
        );
        accept(
            &format!("EVENT, one record, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::data(
                MsgType::Event,
                cipher,
                id,
                epoch,
                300,
                vec![Record::new(Format::None, 7, vec![0xaa])],
            )
            .unwrap(),
        );
        accept(
            &format!("ALARM, one record, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::data(
                MsgType::Alarm,
                cipher,
                id,
                epoch,
                400,
                vec![Record::new(Format::None, 9, vec![0xbb, 0xcc])],
            )
            .unwrap(),
        );
        accept(
            &format!("HEARTBEAT, empty payload, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::control(MsgType::Heartbeat, cipher, id, epoch, 500, &[]).unwrap(),
        );
        accept(
            &format!("EPOCH_ANNOUNCE, collector to node, tag{tag}"),
            &s,
            epoch,
            Direction::CollectorToNode,
            &Datagram::control(
                MsgType::EpochAnnounce,
                cipher,
                id,
                epoch,
                600,
                &Control::EpochAnnounce { target_epoch: epoch + 1 }.encode().unwrap(),
            )
            .unwrap(),
        );
        accept(
            &format!("CAPABILITY_ADVERTISE, tag{tag}"),
            &s,
            epoch,
            n2c,
            &Datagram::control(
                MsgType::CapabilityAdvertise,
                cipher,
                id,
                epoch,
                700,
                &Capability {
                    max_version: 1,
                    ciphers: vec![0x01, 0x04],
                    layouts: vec![(0x01, 1), (0x02, 2)],
                }
                .encode()
                .unwrap(),
            )
            .unwrap(),
        );
    }

    // --- boundary set (PROTOCOL.md 14.1) ---
    accept(
        "boundary: offset 0",
        &s,
        epoch,
        n2c,
        &Datagram::number(CipherId::HmacSha256T32, id, epoch, 0, "1").unwrap(),
    );
    accept(
        "boundary: offset 524287, last tick of the epoch",
        &s,
        epoch,
        n2c,
        &Datagram::number(CipherId::HmacSha256T32, id, epoch, TICKS_PER_EPOCH - 1, "1").unwrap(),
    );
    accept(
        "boundary: offset 65536, first value past a 16-bit read",
        &s,
        epoch,
        n2c,
        &Datagram::number(CipherId::HmacSha256T32, id, epoch, 65_536, "1").unwrap(),
    );
    accept(
        "boundary: size 1",
        &s,
        epoch,
        n2c,
        &Datagram::data(
            MsgType::Message,
            CipherId::HmacSha256T32,
            id,
            epoch,
            1,
            vec![Record::new(Format::None, 1, vec![0x5a])],
        )
        .unwrap(),
    );
    accept(
        "boundary: size 400 and schema_version 255, both straddling bytes",
        &s,
        epoch,
        n2c,
        &Datagram::data(
            MsgType::Message,
            CipherId::HmacSha256T32,
            id,
            epoch,
            2,
            vec![Record::new(Format::CapnProto, 0xff, vec![0x77; 400])],
        )
        .unwrap(),
    );
    accept(
        "boundary: 32-byte NUMBER literal",
        &s,
        epoch,
        n2c,
        &Datagram::number(CipherId::HmacSha256T32, id, epoch, 3, "1.0000000000000000000000000000")
            .unwrap(),
    );
    accept(
        "boundary: reserved bits all set, must be ignored by receivers",
        &s,
        epoch,
        n2c,
        &{
            let mut d = Datagram::number(CipherId::HmacSha256T32, id, epoch, 4, "1").unwrap();
            d.reserved = 0x1F;
            d
        },
    );

    // --- TIME_ANNOUNCE: its own key schedule ---
    let asserted = 1_700_000_000i64;
    let wire = Datagram::time_announce(id, asserted, &s).unwrap();
    println!("# TIME_ANNOUNCE, cipher 0x01 mandatory, keyed on time_key");
    println!("kind         accept_time_announce");
    println!("device_secret {}", hex(&s.0));
    println!("sender_id    {id:08x}");
    println!("time_key     {}", hex(&s.time_key(id)));
    println!("asserted_time {asserted}");
    println!("wire         {}", hex(&wire));
    println!("wire_len     {}", wire.len());
    println!();

    // --- rejected NUMBER literals (PROTOCOL.md 6.3) ---
    println!("# Rejected NUMBER literals: every one MUST fail the grammar of 6.3");
    for bad in [
        "", "23.", ".5", "007", "-0", "-0.0", "+1", "1e3", "1.2.3", "-", "1 2", "1,5", "0x1f",
    ] {
        println!("reject_number {}", if bad.is_empty() { "<empty>" } else { bad });
    }
    println!();
    println!("# Accepted NUMBER literals");
    for ok in ["0", "5", "23.5", "23.50", "-12.75", "1013.25", "0.5", "-0.5"] {
        println!("accept_number {ok}");
    }
}
